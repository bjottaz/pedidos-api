    Cliente NVARCHAR(100) NOT NULL,
    Valor DECIMAL(10,2) NOT NULL,
    Status NVARCHAR(20) NOT NULL DEFAULT 'Criado',
    CriadoEm DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
